FONT = "맑은 고딕"; SIZE = Pt(15)

def set_run(run, text):
    run.text = text
    run.font.name = FONT
    run.font.size = SIZE
    rpr = run._element.get_or_add_rPr()
    rf = rpr.find(qn('w:rFonts'))
    if rf is None:
        rf = rpr.makeelement(qn('w:rFonts'), {}); rpr.append(rf)
    for a in ('w:ascii','w:hAnsi','w:eastAsia','w:cs'):
        rf.set(qn(a), FONT)

def clear_para(p):
    for r in list(p.runs):
        r._element.getparent().remove(r._element)

def fill_cell_answer(cell, paragraphs, keep_prompt_idx=None):
    """마지막 안내문단(‘1,000자…’)을 답변으로 교체. 앞 안내(prompt)는 유지."""
    ps = cell.paragraphs
    # 마지막 문단(placeholder) 위치
    target = ps[-1]
    clear_para(target)
    target.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    set_run(target.add_run(), paragraphs[0])
    for txt in paragraphs[1:]:
        np = cell.add_paragraph()
        np.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        set_run(np.add_run(), txt)

def set_value_cell(cell, text):
    # 셀 내용 지우고 값 입력
    for p in list(cell.paragraphs)[1:]:
        p._element.getparent().remove(p._element)
    p = cell.paragraphs[0]
    clear_para(p)
    set_run(p.add_run(), text)

def remove_table(tbl):
    tbl._element.getparent().remove(tbl._element)

